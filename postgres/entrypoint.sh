#!/usr/bin/env bash
# Wrapper around the official postgres entrypoint.
# Renders runtime config from environment, bootstraps a replica if requested,
# starts the backup scheduler (primary only) and then hands over to docker-entrypoint.sh.
set -Eeuo pipefail

# Anything other than the server itself (e.g. `docker compose run ... bash`) is passed straight through.
if [[ "${1:-}" != "postgres" ]]; then
    exec "$@"
fi
shift

PG_ROLE="${PG_ROLE:-primary}"
PGDATA="${PGDATA:-/var/lib/postgresql/data}"
CONF_DIR=/etc/postgresql
CERT_DIR="${CONF_DIR}/certs"

log() { printf '%s [entrypoint:%s] %s\n' "$(date -u +%FT%TZ)" "${PG_ROLE}" "$*" >&2; }
die() { log "FATAL: $*"; exit 1; }
need() { local v; for v in "$@"; do [[ -n "${!v:-}" ]] || die "environment variable ${v} is required"; done; }

[[ "${PG_ROLE}" == primary || "${PG_ROLE}" == replica ]] || die "PG_ROLE must be 'primary' or 'replica'"
need REPLICATION_PASSWORD
if [[ "${PG_ROLE}" == primary ]]; then
    need POSTGRES_PASSWORD PGBOUNCER_AUTH_PASSWORD MONITOR_PASSWORD
fi
[[ "${BACKUP_ENABLED:-yes}" == yes ]] && need BACKUP_CIPHER_PASS

install -d -m 0750 -o postgres -g postgres "${CONF_DIR}" "${CONF_DIR}/conf.d" \
    /etc/pgbackrest /var/lib/pgbackrest /var/log/pgbackrest /var/spool/pgbackrest
install -d -m 0700 -o postgres -g postgres "${CERT_DIR}"

# ---------------------------------------------------------------- TLS ----
if [[ -n "${TLS_CERT_B64:-}" && -n "${TLS_KEY_B64:-}" ]]; then
    log "using TLS certificate supplied via TLS_CERT_B64/TLS_KEY_B64"
    printf '%s' "${TLS_CERT_B64}" | base64 -d > "${CERT_DIR}/server.crt"
    printf '%s' "${TLS_KEY_B64}"  | base64 -d > "${CERT_DIR}/server.key"
else
    log "generating self-signed TLS certificate (set TLS_CERT_B64/TLS_KEY_B64 for a real one)"
    openssl req -x509 -newkey rsa:3072 -sha256 -days 825 -nodes \
        -subj "/CN=${TLS_CN:-postgres}" \
        -keyout "${CERT_DIR}/server.key" -out "${CERT_DIR}/server.crt" 2>/dev/null
fi
chown postgres:postgres "${CERT_DIR}/server.crt" "${CERT_DIR}/server.key"
chmod 0644 "${CERT_DIR}/server.crt"; chmod 0600 "${CERT_DIR}/server.key"

# ------------------------------------------------- environment tuning ----
{
    echo "# generated by pg-entrypoint — do not edit"
    echo "max_connections = ${PG_MAX_CONNECTIONS:-200}"
    echo "shared_buffers = '${PG_SHARED_BUFFERS:-1GB}'"
    echo "effective_cache_size = '${PG_EFFECTIVE_CACHE_SIZE:-3GB}'"
    echo "work_mem = '${PG_WORK_MEM:-16MB}'"
    echo "maintenance_work_mem = '${PG_MAINTENANCE_WORK_MEM:-256MB}'"
    echo "max_wal_size = '${PG_MAX_WAL_SIZE:-4GB}'"
    echo "max_slot_wal_keep_size = '${PG_MAX_SLOT_WAL_KEEP_SIZE:-20GB}'"
    echo "log_min_duration_statement = ${PG_LOG_MIN_DURATION_MS:-1000}"
    if [[ "${PG_ROLE}" == replica ]]; then
        need REPLICA_SLOT
        echo "primary_conninfo = 'host=${PRIMARY_HOST:-postgres-primary} port=5432 user=replicator passfile=/var/lib/postgresql/.pgpass sslmode=require application_name=${REPLICA_SLOT}'"
        echo "primary_slot_name = '${REPLICA_SLOT}'"
    fi
} > "${CONF_DIR}/conf.d/10-env.conf"

# ----------------------------------------------------------- pg_hba ------
{
    echo "# generated by pg-entrypoint — do not edit"
    echo "# TYPE   DATABASE     USER         ADDRESS            METHOD"
    echo "local    all          all                             peer"
    echo "local    replication  all                             peer"
    echo "# never allow the superuser or the replication role over the network for normal DB access"
    echo "host     all          postgres     0.0.0.0/0          reject"
    echo "host     all          postgres     ::/0               reject"
    echo "host     all          replicator   0.0.0.0/0          reject"
    echo "host     all          replicator   ::/0               reject"
    echo "hostnossl all         all          0.0.0.0/0          reject"
    echo "hostnossl all         all          ::/0               reject"
    IFS=',' read -ra cidrs <<< "${PG_ALLOWED_CIDRS:-172.16.0.0/12,10.0.0.0/8,192.168.0.0/16}"
    for c in "${cidrs[@]}"; do
        c="${c//[[:space:]]/}"; [[ -n "${c}" ]] || continue
        [[ "${c}" =~ ^[0-9a-fA-F:.]+/[0-9]+$ ]] || die "invalid CIDR in PG_ALLOWED_CIDRS: ${c}"
        echo "hostssl  replication  replicator   ${c}   scram-sha-256"
        echo "hostssl  all          all          ${c}   scram-sha-256"
    done
} > "${CONF_DIR}/pg_hba.conf"
chown postgres:postgres "${CONF_DIR}/pg_hba.conf" "${CONF_DIR}/conf.d/10-env.conf"
chmod 0640 "${CONF_DIR}/pg_hba.conf" "${CONF_DIR}/conf.d/10-env.conf"

# ------------------------------------------------------- pgBackRest ------
if [[ "${BACKUP_ENABLED:-yes}" == yes ]]; then
    render-pgbackrest-conf
else
    log "backups disabled (BACKUP_ENABLED!=yes) — turning off archive_mode"
    echo "archive_mode = off" >> "${CONF_DIR}/conf.d/10-env.conf"
fi

# ------------------------------------------------- replica bootstrap -----
if [[ "${PG_ROLE}" == replica ]]; then
    PRIMARY_HOST="${PRIMARY_HOST:-postgres-primary}"
    # libpq passfile: escape \ and : per the .pgpass format
    esc() { local s="${1//\\/\\\\}"; printf '%s' "${s//:/\\:}"; }
    printf '%s:5432:*:replicator:%s\n' "${PRIMARY_HOST}" "$(esc "${REPLICATION_PASSWORD}")" \
        > /var/lib/postgresql/.pgpass
    chown postgres:postgres /var/lib/postgresql/.pgpass; chmod 0600 /var/lib/postgresql/.pgpass

    if [[ ! -s "${PGDATA}/PG_VERSION" ]]; then
        log "empty data directory — cloning ${PRIMARY_HOST} with pg_basebackup"
        until pg_isready -q -h "${PRIMARY_HOST}" -p 5432; do log "waiting for primary..."; sleep 3; done
        install -d -m 0700 -o postgres -g postgres "${PGDATA}"
        run_basebackup() {
            gosu postgres env PGSSLMODE=require PGPASSFILE=/var/lib/postgresql/.pgpass \
                pg_basebackup -h "${PRIMARY_HOST}" -U replicator -D "${PGDATA}" \
                -X stream --checkpoint=fast -S "${REPLICA_SLOT}" "$@"
        }
        if ! run_basebackup -C; then
            log "slot may already exist — retrying with the existing slot"
            find "${PGDATA}" -mindepth 1 -delete
            run_basebackup
        fi
        touch "${PGDATA}/standby.signal"
        chown postgres:postgres "${PGDATA}/standby.signal"
        log "replica cloned"
    fi
fi

# ----------------------------------------------- backup scheduler --------
if [[ "${PG_ROLE}" == primary && "${BACKUP_ENABLED:-yes}" == yes ]]; then
    gosu postgres backup-agent &
fi

exec docker-entrypoint.sh postgres -c "config_file=${CONF_DIR}/postgresql.conf" "$@"
